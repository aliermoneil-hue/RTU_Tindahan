"""Catalogue API: browsing, posting, and the moderation decision.

Endpoints are generated by the router in `apps/catalog/urls.py`:

    GET    /api/v1/categories/                       public
    GET    /api/v1/listings/                         public (approved only)
    GET    /api/v1/listings/<slug>/                  public (approved only)
    POST   /api/v1/listings/                         verified members
    PATCH  /api/v1/listings/<slug>/                  the seller
    DELETE /api/v1/listings/<slug>/                  the seller
    POST   /api/v1/listings/<slug>/approve/          moderators
    POST   /api/v1/listings/<slug>/reject/           moderators

Listings are created as `pending_screening` and published only by an approve
call, which keeps LS-05/AI-02 true even before the screening service exists.
"""

from decimal import Decimal, InvalidOperation

from django.conf import settings
from django.db.models import Avg, Case, Count, F, IntegerField, OuterRef, Q, Subquery, Value, When
from django.db.models.functions import Coalesce
from rest_framework import serializers, status, viewsets
from rest_framework.decorators import action
from rest_framework.exceptions import PermissionDenied, ValidationError
from rest_framework.parsers import FormParser, JSONParser, MultiPartParser
from rest_framework.permissions import AllowAny
from rest_framework.response import Response

from apps.accounts.models import User
from apps.accounts.permissions import IsAdministrator, IsModerator, IsVerifiedUser
from apps.audit.services import record
from apps.notifications.services import notify
from apps.screening.services import record_moderator_decision, run_screening

from .models import Category, Listing
from .serializers import (
    CategorySerializer,
    ListingReadSerializer,
    ListingWriteSerializer,
)

# Every mode ends with a tie-breaker so that paging is stable: without one,
# two listings posted in the same second can swap places between requests and
# a visitor sees the same row twice.
ORDERING = {
    # BD-07: the default feed. `None` means "annotate a score and sort by it" —
    # the score itself lives in apps/catalog/feed.py, with the weights in settings.
    "recommended": None,
    "newest": ("-created_at",),
    "oldest": ("created_at",),
    "price": ("price", "-created_at"),
    "-price": ("-price", "-created_at"),
    "popular": ("-view_count", "-created_at"),
    # BD-03/BD-07: done by the sales counter, which a claimed ticket raises.
    "best-selling": ("-sold_count", "-created_at"),
    "least-sold": ("sold_count", "-created_at"),
    # The "small sellers" product decision: a verified student whose active
    # catalogue is no bigger than SMALL_SELLER_MAX_LISTINGS comes first, then
    # the smallest catalogues, then the newest. Both fields are annotated in
    # get_queryset.
    "small-sellers": ("-seller_is_small", "seller_active_listings", "-created_at"),
}
TRUE_VALUES = {"1", "true", "yes"}
MODERATION_VALUES = {choice for choice, _ in Listing.ModerationStatus.choices}
AVAILABILITY_VALUES = {choice for choice, _ in Listing.AvailabilityStatus.choices}
# What `?status=` accepted before the split, kept so existing callers (the
# moderator queue included) keep working unchanged.
STATUS_VALUES = MODERATION_VALUES | AVAILABILITY_VALUES


def price_bound(params, key):
    """Read a price bound from the query string, or None when it is absent.

    A bad value is reported instead of ignored: a visitor who filters
    `max_price=abc` and silently receives the whole catalogue would think the
    filter is broken.
    """
    raw = (params.get(key) or "").strip()
    if not raw:
        return None
    try:
        value = Decimal(raw)
    except (InvalidOperation, ValueError, TypeError):
        raise ValidationError({key: "Enter a number, for example 150 or 150.00."})
    if value < 0:
        raise ValidationError({key: "Price cannot be negative."})
    return value


class CategoryViewSet(viewsets.ModelViewSet):
    """AD-03 and MN-02: an administrator edits the marketplace categories.

    Reading is open — the browse screen and the listing form need the list — and
    every write is administrator-only, audited, and refuses to break a listing
    that already sits in the category. Deactivating is the safe way to retire a
    category: the listings keep theirs, and it stops being offered for new ones.
    """

    serializer_class = CategorySerializer
    lookup_field = "slug"
    pagination_class = None

    def get_permissions(self):
        if self.action in ("list", "retrieve"):
            return [AllowAny()]
        return [IsAdministrator()]

    def get_queryset(self):
        queryset = Category.objects.select_related("parent").annotate(
            listing_count=Count("listings", distinct=True)
        )
        # The pickers ask for what is offered; the panel asks for everything.
        wants_all = self.request.query_params.get("all") in {"1", "true", "yes"}
        user = getattr(self.request, "user", None)
        staff = bool(user and user.is_authenticated and user.is_moderator)
        if self.action in ("list", "retrieve") and not (wants_all and staff):
            queryset = queryset.filter(is_active=True)
        return queryset

    def perform_create(self, serializer):
        category = serializer.save()
        record(
            self.request.user,
            "create category",
            target_type="category",
            target_id=category.slug,
            target_name=category.name,
        )

    def perform_update(self, serializer):
        before = serializer.instance
        changes = {
            field: getattr(before, field)
            for field in ("name", "parent_id", "sort_order", "is_active")
        }
        category = serializer.save()
        after = {
            field: getattr(category, field)
            for field in ("name", "parent_id", "sort_order", "is_active")
        }
        diff = {k: (changes[k], after[k]) for k in changes if changes[k] != after[k]}
        record(
            self.request.user,
            "edit category",
            target_type="category",
            target_id=category.slug,
            target_name=category.name,
            note=str(diff)[:300],
        )

    def perform_destroy(self, instance):
        """Refuse a delete that would orphan listings; deactivate instead."""
        if instance.listings.exists() or instance.children.exists():
            raise serializers.ValidationError(
                {
                    "detail": "This category still has listings or sub-categories. "
                    "Turn it off instead, so nothing loses its place."
                }
            )
        name, slug = instance.name, instance.slug
        instance.delete()
        record(
            self.request.user,
            "delete category",
            target_type="category",
            target_id=slug,
            target_name=name,
        )


class ListingViewSet(viewsets.ModelViewSet):
    lookup_field = "slug"
    parser_classes = [MultiPartParser, FormParser, JSONParser]

    def get_queryset(self):
        user = self.request.user
        params = self.request.query_params
        queryset = Listing.objects.select_related("seller", "category").prefetch_related(
            "photos", "variants", "screening_results"
        )
        # Item ratings come from verified completed orders. Seller reviews have
        # no listing, so this join only ever counts item reviews.
        # RR-07 with RR-06: only a published review counts towards the average.
        # A held edit is out until a moderator releases it.
        published = Q(reviews__moderation_status="visible")
        queryset = queryset.annotate(
            rating_avg=Avg("reviews__stars", filter=published),
            rating_count=Count("reviews", filter=published),
        )

        # "Small sellers": the size of each seller's live catalogue, counted in
        # a subquery so it cannot multiply the review join above. A student
        # with at most SMALL_SELLER_MAX_LISTINGS approved, available listings
        # is small; the flag and the count drive the small-sellers ordering.
        active_catalogue = (
            Listing.objects.filter(
                seller=OuterRef("seller"),
                moderation_status=Listing.ModerationStatus.APPROVED,
                availability_status=Listing.AvailabilityStatus.AVAILABLE,
                seller__status="active",
            )
            .order_by()
            .values("seller")
            .annotate(n=Count("pk"))
            .values("n")
        )
        queryset = queryset.annotate(
            seller_active_listings=Coalesce(
                Subquery(active_catalogue, output_field=IntegerField()),
                Value(0),
            )
        ).annotate(
            seller_is_small=Case(
                When(
                    seller__member_type=User.MemberType.STUDENT,
                    seller_active_listings__lte=settings.SMALL_SELLER_MAX_LISTINGS,
                    then=Value(1),
                ),
                default=Value(0),
                output_field=IntegerField(),
            )
        )

        # Visibility: staff see every status, a seller sees their own rows only
        # when they ask for them, and everyone else sees only approved listings
        # that are still available (BD-01, LS-05).
        #
        # "Ask for them" is explicit: ?seller=me (the seller dashboard) or any
        # status filter (the moderation queue). The bare /listings/ call is the
        # marketplace, so an unpublished listing must never ride along there —
        # the browser has no way to tell the two apart, and a pending item
        # showed up in the shop grid the moment its seller was signed in.
        # Retrieve stays owner-permissive: the page opened right after
        # publishing, and the edit screen behind it, must be able to read the
        # seller's own unpublished listing.
        visible = Q(
            moderation_status=Listing.ModerationStatus.APPROVED,
            availability_status=Listing.AvailabilityStatus.AVAILABLE,
            # AD-01: a suspended or banned seller's listings leave the
            # marketplace without anyone having to delete them by hand.
            seller__status="active",
            seller__is_active=True,
        )
        own = Q(seller=user)
        asked_for_own = params.get("seller") == "me" or any(
            params.get(name)
            for name in (
                "status",
                "moderation_status",
                "moderation",
                "availability_status",
                "availability",
            )
        )
        if user.is_authenticated and user.is_moderator:
            pass
        elif user.is_authenticated:
            # Detail routes are for the owner as much as the marketplace.
            # Without this, a seller could not edit or delete a listing that
            # was still waiting for approval: the row simply was not in the
            # queryset, so the delete answered 404.
            owner_actions = {"retrieve", "update", "partial_update", "destroy"}
            if self.action in owner_actions or asked_for_own:
                queryset = queryset.filter(visible | own)
            else:
                queryset = queryset.filter(visible)
        else:
            queryset = queryset.filter(visible)

        def asked_values(name):
            raw = params.get(name)
            if not raw:
                return []
            return [
                value.strip().lower() for value in raw.split(",") if value.strip()
            ]

        def check_known(name, values, valid):
            unknown = [value for value in values if value not in valid]
            if unknown:
                raise ValidationError(
                    {
                        name: f"Unknown {name}: {', '.join(unknown)}. "
                        f"Valid values: {', '.join(sorted(valid))}."
                    }
                )

        # AI-03: the moderator queue asks for one moderation state at a time,
        # e.g. ?status=pending_screening or ?status=pending_screening,needs_review.
        # The visibility filter above already limits a visitor to approved
        # listings, so narrowing here cannot reveal anything new.
        #
        # `status` is the pre-split parameter and still works: moderation values
        # narrow moderation_status, availability values narrow
        # availability_status, and a mixed list narrows both.
        legacy = asked_values("status")
        check_known("status", legacy, STATUS_VALUES)
        moderation_asked = [v for v in legacy if v in MODERATION_VALUES]
        availability_asked = [v for v in legacy if v in AVAILABILITY_VALUES]

        explicit_moderation = asked_values("moderation_status") or asked_values(
            "moderation"
        )
        check_known("moderation_status", explicit_moderation, MODERATION_VALUES)
        moderation_asked += explicit_moderation

        explicit_availability = asked_values("availability_status") or asked_values(
            "availability"
        )
        check_known("availability_status", explicit_availability, AVAILABILITY_VALUES)
        availability_asked += explicit_availability

        if moderation_asked:
            queryset = queryset.filter(moderation_status__in=set(moderation_asked))

        # AI-11: `?awaiting=ai` narrows a rejected queue to the rows the
        # screening rejected and no moderator has confirmed or reversed, which
        # is what the moderation screen actually wants to show.
        awaiting = (params.get("awaiting") or "").strip().lower()
        if awaiting == "ai":
            queryset = queryset.filter(
                moderation_status=Listing.ModerationStatus.REJECTED,
                screening_results__verdict="rejected",
                screening_results__decision="",
            ).distinct()
        if availability_asked:
            queryset = queryset.filter(availability_status__in=set(availability_asked))
        if category := params.get("category"):
            queryset = queryset.filter(category__slug=category)
        if search := params.get("search"):
            queryset = queryset.filter(
                Q(title__icontains=search) | Q(description__icontains=search)
            )
        if listing_type := params.get("type"):
            queryset = queryset.filter(listing_type=listing_type)
        # BD-06: price range. Both bounds are optional and inclusive.
        min_price = price_bound(params, "min_price")
        max_price = price_bound(params, "max_price")
        if min_price is not None and max_price is not None and min_price > max_price:
            raise ValidationError(
                {"max_price": "The maximum price is below the minimum price."}
            )
        if min_price is not None:
            queryset = queryset.filter(price__gte=min_price)
        if max_price is not None:
            queryset = queryset.filter(price__lte=max_price)
        if (official := params.get("official")) is not None:
            queryset = queryset.filter(is_official=official.lower() in TRUE_VALUES)
        if params.get("seller") == "me" and user.is_authenticated:
            queryset = queryset.filter(seller=user)
        # BD-07: the feed is a hybrid score by default, and a search folds text
        # relevance into the same score. Both are computed in SQL, over the whole
        # catalogue rather than over a page of it.
        ordering = params.get("ordering")
        if ordering not in ORDERING:
            ordering = "recommended"
        if ORDERING[ordering] is None:
            from .feed import annotate_feed_score

            queryset = annotate_feed_score(queryset, search=params.get("search", ""))
            queryset = queryset.order_by("-feed_score", "-created_at")
        else:
            queryset = queryset.order_by(*ORDERING[ordering])
        return queryset

    def get_serializer_class(self):
        if self.action in {"create", "update", "partial_update"}:
            return ListingWriteSerializer
        return ListingReadSerializer

    def get_permissions(self):
        if self.action in {"list", "retrieve"}:
            return [AllowAny()]
        if self.action in {"create", "update", "partial_update", "destroy"}:
            # BR-01: only verified RTU members may sell.
            return [IsVerifiedUser()]
        return [IsModerator()]

    def _check_owner(self, listing):
        if listing.seller_id != self.request.user.id:
            raise PermissionDenied("You can only change your own listings.")

    def create(self, request, *args, **kwargs):
        serializer = self.get_serializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        listing = serializer.save()
        # AI-01: every new listing is screened before anyone can see it. A
        # flagged verdict moves it to needs_review; a clean one keeps waiting
        # for a moderator, because screening never publishes on its own.
        run_screening(listing)
        # Answer with the read shape so the client gets the id and slug back.
        return Response(
            ListingReadSerializer(
                listing, context=self.get_serializer_context()
            ).data,
            status=status.HTTP_201_CREATED,
        )

    def update(self, request, *args, **kwargs):
        partial = kwargs.pop("partial", False)
        listing = self.get_object()
        self._check_owner(listing)

        serializer = ListingWriteSerializer(
            listing,
            data=request.data,
            partial=partial,
            context=self.get_serializer_context(),
        )
        serializer.is_valid(raise_exception=True)
        serializer.save()
        # An edit changes the words a moderator would have judged, so the
        # listing is screened again. A clean verdict leaves the status alone;
        # a flagged one pulls it back to needs_review.
        run_screening(listing)
        return Response(
            ListingReadSerializer(
                listing, context=self.get_serializer_context()
            ).data
        )

    def perform_destroy(self, instance):
        self._check_owner(instance)
        instance.delete()

    def retrieve(self, request, *args, **kwargs):
        listing = self.get_object()
        Listing.objects.filter(pk=listing.pk).update(view_count=F("view_count") + 1)
        listing.refresh_from_db(fields=["view_count"])
        return Response(self.get_serializer(listing).data)

    @action(detail=True, methods=["post"], permission_classes=[IsModerator])
    def approve(self, request, slug=None):
        listing = self.get_object()
        listing.approve()
        # AI-11: approving a listing the screening rejected is a reversal, and
        # the row records that the human overruled the machine.
        record_moderator_decision(
            target=listing,
            decision="reversed",
            moderator=request.user,
            note=(request.data.get("note") or "").strip(),
        )
        record(
            request.user,
            "approve listing",
            target_type="listing",
            target_id=listing.slug,
            target_name=listing.title,
        )
        notify(
            listing.seller,
            f"Your listing \u201c{listing.title}\u201d is now live.",
            kind="listing",
            link_kind="shop",
            actor=request.user,
        )
        return Response(self.get_serializer(listing).data)

    @action(detail=True, methods=["post"], permission_classes=[IsModerator])
    def reject(self, request, slug=None):
        reason = (request.data.get("reason") or "").strip()
        if not reason:
            return Response(
                {"reason": "A reason is required when rejecting a listing."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        listing = self.get_object()
        listing.reject(reason)
        record_moderator_decision(
            target=listing,
            decision="confirmed",
            moderator=request.user,
            note=reason,
        )
        record(
            request.user,
            "reject listing",
            target_type="listing",
            target_id=listing.slug,
            target_name=listing.title,
            note=reason,
        )
        notify(
            listing.seller,
            f"Your listing \u201c{listing.title}\u201d was not approved: {reason}",
            kind="listing",
            link_kind="shop",
            actor=request.user,
        )
        return Response(self.get_serializer(listing).data)
